/* ============================================================================
   build-seo.mjs — makes the site readable by Google.
   ----------------------------------------------------------------------------
   WHY THIS EXISTS
   The two .dc.html pages draw everything with JavaScript after loading React
   and Babel from a CDN. A search engine that fetches the page sees an empty
   shell. This script reads content.js and diary.js and writes real pages whose
   text, title, description and structured data are already in the HTML. The
   interactive site then mounts on top, so visitors see no difference.

   YOU NEVER EDIT THE FILES THIS WRITES. They are regenerated by publish.sh
   every time the site is published:

     index.html                 English home page      https://tkuhara.github.io/
     ja.html                    Japanese home page
     project-<id>.html          one page per project (English)
     project-<id>-ja.html       one page per project (Japanese)
     diary.html                 the diary
     sitemap.xml, robots.txt    the map Google reads

   Run by hand:   node build-seo.mjs
   No dependencies — plain Node 18+.
   ========================================================================== */

