/* ---- assemble ------------------------------------------------------------ */
const portfolio = splitDc(PORTFOLIO_SRC);
const diary = splitDc(DIARY_SRC);
const out = {};
const sitemap = [];
const contentStamp = new Date(Math.max(mtime('content.js'), mtime(PORTFOLIO_SRC)));
const contentDate = isoDate(contentStamp);                                   // sitemap: date only
// Google's structured-data checker rejects a bare date here — it wants a full
// ISO 8601 timestamp with a timezone.
const contentDateTime = contentStamp.toISOString().replace(/\.\d+Z$/, 'Z');

for (const lang of LANGS) {
  const alternates = [
    { lang: 'en', href: homeUrl('en') }, { lang: 'ja', href: homeUrl('ja') }, { lang: 'x-default', href: homeUrl('en') }
  ];
  out[lang === 'en' ? 'index.html' : 'ja.html'] = page(head({
    lang, title: tr(SEO.title, lang), description: tr(SEO.description, lang),
    canonical: homeUrl(lang), alternates, image: C.PROJECTS.find(p => p.image)?.image || C.PROFILE.portrait,
    type: 'profile', stylesheet: portfolio.sheet,
    ld: [websiteLd, personLd(lang),
      { '@type': 'ProfilePage', '@id': homeUrl(lang) + '#page', url: homeUrl(lang), name: tr(SEO.title, lang), inLanguage: lang, isPartOf: { '@id': SITE + '/#website' }, mainEntity: { '@id': PERSON_ID }, dateModified: contentDateTime },
      ...(lang === 'en' ? C.PUBLICATIONS.map(articleLd) : [])],
    site: { lang, alt: homeFile(other(lang)), home: homeFile(lang), projectUrl: projFile('{id}', lang) },
    redirectToAlt: lang === 'en' ? homeFile('ja') : null
  }), portfolio, homeBody(lang), lang);
  sitemap.push({ loc: homeUrl(lang), lastmod: contentDate, alternates, priority: '1.0' });

  for (const p of C.PROJECTS) {
    const url = l => SITE + '/' + projFile(p.id, l);
    const palt = [{ lang: 'en', href: url('en') }, { lang: 'ja', href: url('ja') }, { lang: 'x-default', href: url('en') }];
    const name = tr(C.PROFILE.name, lang);
    const title = `${tr(p.title, lang)} | ${name}`;
    const doi = [p.links?.doi, ...(p.links?.more || []).map(m => m.href)].filter(u => u && /doi\.org/.test(u));
    out[projFile(p.id, lang)] = page(head({
      lang, title, description: clip(tr(p.blurb, lang), lang === 'ja' ? 120 : 165),
      canonical: url(lang), alternates: palt, image: p.image || C.PROFILE.portrait, type: 'article', stylesheet: portfolio.sheet,
      ld: [websiteLd, personLd(lang),
        { '@type': 'WebPage', '@id': url(lang) + '#page', url: url(lang), name: title, inLanguage: lang, isPartOf: { '@id': SITE + '/#website' }, dateModified: contentDateTime,
          primaryImageOfPage: p.image ? abs(p.image) : undefined,
          mainEntity: { '@type': 'ResearchProject', name: tr(p.title, lang), description: tr(p.blurb, lang), member: { '@id': PERSON_ID }, sameAs: doi.length ? doi : undefined },
          breadcrumb: { '@type': 'BreadcrumbList', itemListElement: [
            { '@type': 'ListItem', position: 1, name, item: homeUrl(lang) },
            { '@type': 'ListItem', position: 2, name: tr(p.title, lang), item: url(lang) }] } }],
      site: { lang, view: p.id, alt: projFile(p.id, other(lang)), home: homeFile(lang), projectUrl: projFile('{id}', lang) },
      redirectToAlt: lang === 'en' ? projFile(p.id, 'ja') : null
    }), portfolio, projectBody(p, lang), lang);
    sitemap.push({ loc: url(lang), lastmod: contentDate, alternates: palt, priority: '0.8' });
  }
}

const diaryUrl = SITE + '/diary.html';
const diaryDate = entriesSorted[0]?.date || isoDate(mtime('diary.js'));
out['diary.html'] = page(head({
  lang: 'en', title: SEO.diaryTitle, description: SEO.diaryDescription, canonical: diaryUrl,
  image: C.PROFILE.portrait, stylesheet: diary.sheet,
  ld: [websiteLd, personLd('en'), {
    '@type': 'Blog', '@id': diaryUrl + '#blog', url: diaryUrl, name: SEO.diaryTitle, author: { '@id': PERSON_ID },
    blogPost: entriesSorted.map(e => ({ '@type': 'BlogPosting', headline: e.title, datePublished: e.date + 'T12:00:00Z', inLanguage: e.lang || 'en', author: { '@id': PERSON_ID }, url: diaryUrl, articleBody: (e.body || []).filter(b => typeof b === 'string').join('\n\n') }))
  }],
  site: { page: 'diary' }
}), diary, diaryBody(), 'en', true);
sitemap.push({ loc: diaryUrl, lastmod: diaryDate, priority: '0.6' });

out['sitemap.xml'] = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${sitemap.map(u => `  <url>
    <loc>${esc(u.loc)}</loc>
    <lastmod>${u.lastmod}</lastmod>
${(u.alternates || []).map(a => `    <xhtml:link rel="alternate" hreflang="${a.lang}" href="${esc(a.href)}"/>`).join('\n')}
    <priority>${u.priority}</priority>
  </url>`).join('\n').replace(/\n\n/g, '\n')}
</urlset>
`;
out['robots.txt'] = `User-agent: *\nAllow: /\n\nSitemap: ${SITE}/sitemap.xml\n`;

// Everything rendered without throwing — only now touch the disk.
let changed = 0;
for (const [file, text] of Object.entries(out)) {
  const old = existsSync(at(file)) ? readFileSync(at(file), 'utf8') : null;
  if (old !== text) { writeFileSync(at(file), text); changed++; }
}
console.log(`build-seo: ${Object.keys(out).length} files checked, ${changed} written`);
