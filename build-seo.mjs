function splitDc(file) {
  const src = readFileSync(at(file), 'utf8');
  const open = src.indexOf('<x-dc');
  const close = src.lastIndexOf('</x-dc>') + '</x-dc>'.length;
  const scriptStart = src.indexOf('<script type="text/x-dc"');
  const scriptEnd = src.indexOf('</script>', scriptStart) + '</script>'.length;
  if (open < 0 || close < 7 || scriptStart < 0) throw new Error(file + ': could not find <x-dc> block or its script');
  const sheet = (/<link rel="stylesheet" href="([^"]+)"/.exec(src) || [])[1];
  if (!sheet) throw new Error(file + ': stylesheet link not found');
  return { template: src.slice(open, close), script: src.slice(scriptStart, scriptEnd), sheet };
}

