function linksOf(o, ui) {
  const out = [];
  if (o.doi) out.push({ label: ui.link_doi, href: o.doi });
  if (o.arxiv) out.push({ label: 'arXiv', href: o.arxiv });
  if (o.pdf) out.push({ label: ui.link_pdf, href: o.pdf });
  if (o.video) out.push({ label: ui.link_video, href: o.video });
  if (o.page) out.push({ label: 'Page', href: o.page });
  if (o.code) out.push({ label: 'Code', href: o.code });
  (o.more || []).forEach(l => l && l.href && out.push({ label: l.label || 'Link', href: l.href }));
  return out;
}
